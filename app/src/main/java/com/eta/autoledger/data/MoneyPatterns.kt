package com.eta.autoledger.data

/**
 * 金额正则的共享原子表达式。
 *
 * 内置解析、系统规则播种和规则编辑器必须引用同一组片段，避免“元”后缀、
 * 货币符号或千分位语法在其中一处更新、另外两处继续漂移。
 */
object MoneyPatterns {

    /** 带千分位或普通小数的正金额，最多两位小数。 */
    const val NUMBER = """(?:\d{1,3}(?:,\d{3})+(?:\.\d{1,2})?|\d+(?:\.\d{1,2})?)"""

    /** 可选货币符号 + [NUMBER] + 可选“元/圆”后缀，金额在第一个分组。 */
    const val WITH_YUAN = """(?:[¥￥]\s*)?($NUMBER)\s*(?:元|圆)"""

    /** 可选货币符号 + [NUMBER]，金额在第一个分组。 */
    const val WITH_CURRENCY = """(?:[¥￥]\s*)?($NUMBER)"""

    /** 必须有货币符号 + [NUMBER]。 */
    const val WITH_SYMBOL = """[¥￥]\s*($NUMBER)"""

    /** 交易动词后 12 个非金额字符内的金额，避免抓到余额和可用额度。 */
    const val NEAR_VERB = """(?:消费|支付|付款|支出|扣款|扣费|转账|转出|转入|收入|存入|入账|取现|还款|退款|缴费|缴纳|购买|充值|提现|收款|收到|交易)[^\d¥￥]{0,12}(?:[¥￥]\s*)?($NUMBER)"""

    /** 编辑器默认金额正则：要求“元/圆”，减少把余额或订单号误当金额。 */
    const val EDITOR_DEFAULT = WITH_YUAN
}
